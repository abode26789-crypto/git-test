Diwaniya _createDiwaniya({
  required String id,
  required String name,
  required String location,
  required double distanceKm,
  required double rating,
  required int reviewCount,
  required int photoIndex,
  required List<String> facilities,
  required List<String> activities,
  required String type,
  required String openingTime,
  required String closingTime,
  required String description,
  required bool isOpenNow,
  required int variant,
}) {
  final imageUrl = _photoUrls[photoIndex % _photoUrls.length];
  return Diwaniya(
    id: id,
    name: name,
    location: location,
    distanceKm: distanceKm,
    rating: rating,
    reviewCount: reviewCount,
    imageUrl: imageUrl,
    galleryUrls: List.generate(
      3,
      (index) => _photoUrls[(photoIndex + index) % _photoUrls.length],
    ),
    facilities: facilities,
    activities: activities,
    type: type,
    openingTime: openingTime,
    closingTime: closingTime,
    description: description,
    isOpenNow: isOpenNow,
    sessions: _createSessions(id, variant, facilities),
  );
}

